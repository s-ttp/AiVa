"""Render generated documents in a sandboxed, network-less subprocess (PLAN §3, LLD §20 rendering isolation).

Layers, each independent of the others:
- Only files the gateway generated are rendered. The caller passes the bytes and the SHA-256 recorded at
  generation, and the sandbox refuses bytes whose hash differs. There is no upload path.
- `python -I`: no user site, no PYTHON* variables, no current-directory imports.
- An empty environment: no proxies, no credentials, no HOME.
- A throwaway working directory.
- An audit hook in the child refuses network, subprocess, file-write, file-metadata and `ctypes` events
  before any document library is imported (`artifacts.render`).
- Resource limits, set by the child before it reads its input: address space, CPU time, file size 0, open
  files, no core dumps. A wall-clock timeout kills the child.
- An OS layer, installed by the child before anything else runs (`artifacts.oslayer`): a seccomp filter
  that refuses sockets, exec, process creation, signals and pidfd access to other processes at the kernel,
  which also binds native code; plus an empty network namespace where the kernel allows one. Without the
  seccomp filter the child renders nothing. The gateway process itself is made non-dumpable before the
  first child, so a child cannot read or write its memory.
"""

import asyncio
import hashlib
import json
import sys
import tempfile
import time
from dataclasses import dataclass
from typing import Any

from aiva_gateway.core.errors import AivaError

RENDERER_VERSION = "aiva-sandbox-ooxml-v1"
TIMEOUT_SECONDS = 20.0
MAX_DOCUMENT_BYTES = 5 * 1024 * 1024


class SandboxError(AivaError):
    status_code = 422
    code = "ARTIFACT_RENDER_FAILED"


@dataclass(frozen=True)
class Rendered:
    pages: list[dict[str, Any]]
    stats: dict[str, int]
    protected: bool
    title: str | None
    verified_sha256: str
    duration_ms: float


_parent_protected = False


def _protect_parent() -> None:
    """Once per gateway process, before the first child: non-dumpable, so a render child (same uid) can
    neither open `/proc/<gateway>/mem` nor take the gateway's file descriptors. Fails closed."""
    global _parent_protected
    if _parent_protected:
        return
    from aiva_gateway.artifacts import oslayer

    try:
        oslayer.make_undumpable()
    except OSError as exc:
        raise SandboxError("The sandbox could not protect the gateway process.") from exc
    _parent_protected = True


async def _run(args: list[str], stdin: bytes) -> tuple[int, bytes, bytes]:
    _protect_parent()
    with tempfile.TemporaryDirectory(prefix="aiva-render-") as workdir:
        process = await asyncio.create_subprocess_exec(
            sys.executable,
            "-I",
            "-m",
            "aiva_gateway.artifacts.render",
            *args,
            stdin=asyncio.subprocess.PIPE,
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.PIPE,
            cwd=workdir,
            env={},
            start_new_session=True,
        )
        try:
            stdout, stderr = await asyncio.wait_for(process.communicate(stdin), TIMEOUT_SECONDS)
        except TimeoutError as exc:
            process.kill()
            await process.wait()
            raise SandboxError("Rendering the document timed out in the sandbox.") from exc
    return process.returncode or 0, stdout, stderr


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


async def render(data: bytes, document_type: str, *, expected_sha256: str) -> Rendered:
    """Open a generated document in the sandbox. Refuses bytes that are not the recorded artifact."""
    digest = sha256(data)
    if digest != expected_sha256:
        raise SandboxError(
            "Only documents generated by AiVa are rendered: the file does not match its recorded hash.",
            code="ARTIFACT_NOT_GENERATED",
        )
    if len(data) > MAX_DOCUMENT_BYTES:
        raise SandboxError("The document is too large to render.", code="ARTIFACT_TOO_LARGE")
    started = time.perf_counter()
    code, stdout, _ = await _run([document_type], data)
    try:
        result = json.loads(stdout or b"{}")
    except ValueError as exc:
        raise SandboxError("The sandbox returned no readable result.") from exc
    if code != 0 or "error" in result:
        raise SandboxError(f"The sandbox could not open the document ({result.get('error', code)}).")
    return Rendered(
        pages=result["pages"],
        stats=result["stats"],
        protected=bool(result["protected"]),
        title=result.get("title"),
        verified_sha256=digest,
        duration_ms=(time.perf_counter() - started) * 1000,
    )


async def probe(port: int = 9, parent_fd: int = -1) -> dict[str, str]:
    """What the sandbox refuses (network, DNS, subprocess, file write, and the same at native level: a
    connect to 127.0.0.1:`port`, signalling the gateway, taking its descriptor `parent_fd` through a pidfd
    and writing to it, opening its memory): used by tests and readiness."""
    _, stdout, _ = await _run(["--probe", str(port), str(parent_fd)], b"")
    result: dict[str, str] = json.loads(stdout)["probe"]
    return result


async def layers() -> dict[str, str]:
    """The OS isolation in force in the child: `seccomp` and `network_namespace`."""
    _, stdout, _ = await _run(["--probe"], b"")
    result: dict[str, str] = json.loads(stdout)["layers"]
    return result
