def test_samples_are_valid_requests_with_figures_in_their_sources() -> None:
    catalog = load_catalog(CONFIG)
    copilot = catalog.scenario("document-copilot")
    assert copilot is not None and copilot.sample_artifact is not None
    request = ArtifactCreateRequest.model_validate(copilot.sample_artifact.model_dump())
    sources = {e.id: e.text for e in request.evidence}
    assert request.figures and all(f.value in sources[f.source_id] for f in request.figures)
    agent = catalog.scenario("agentic-workflow")
    assert agent is not None and agent.sample_workflow is not None
    assert AgentWorkflowRequest.model_validate(agent.sample_workflow.model_dump()).incident_id == "INC-7781"


def test_the_scenario_5_sample_is_its_fixture() -> None:
    """The Test Console's default scenario-5 chat is the request its primary proof tests: the same prompt and
    the same 60 synthetic alarms, in the same order (the public replay recordings depend on both)."""
    fixture = json.loads((FIXTURES / "network-operations.json").read_text(encoding="utf-8"))["request"]
    noc = load_catalog(CONFIG).scenario("network-operations")
    assert noc is not None and noc.sample_evidence is not None
    assert [{"role": "user", "content": noc.sample_prompt}] == fixture["messages"]
    assert [e.model_dump() for e in noc.sample_evidence] == fixture["evidence"]
    assert len(noc.sample_evidence) == 60


def test_each_default_chat_carries_its_scenarios_synthetic_source_verbatim() -> None:
    """A default chat without its evidence invents what it lacks (the first recording run did). Each one
    carries the source its proof uses, generated by the same code that produces it elsewhere."""
    catalog = load_catalog(CONFIG)

    def evidence(scenario_id: str) -> list[dict[str, str]]:
        scenario = catalog.scenario(scenario_id)
        assert scenario is not None and scenario.sample_evidence is not None
        return [e.model_dump() for e in scenario.sample_evidence]

    # 1: the add-on passage that explains the 15 AED increase, rendered as retrieval renders it.
    lines = (FIXTURES / "kb_scenarios.jsonl").read_text(encoding="utf-8").splitlines()
    tariff = next(d for d in map(json.loads, lines) if d["doc_id"] == "KB-TARIFF-020")
    text = evidence_text("KB-TARIFF-020", 1, tariff["title"], tariff["section"], tariff["text"])
    assert evidence("customer-support") == [{"id": "KB-TARIFF-020#0", "text": text}]
    # 3: the fixture's prompt and its six alert events, in fixture order.
    fraud = json.loads((FIXTURES / "fraud-management.json").read_text(encoding="utf-8"))["request"]
    investigator = catalog.scenario("fraud-management")
    assert investigator is not None and investigator.sample_prompt == fraud["messages"][-1]["content"]
    assert evidence("fraud-management") == fraud["evidence"]
    # 6: what the workflow's own tools return for INC-7781.
    ops = SyntheticOperations.load()
    sites = ",".join(ops.incident("INC-7781").affected_sites)
    assert evidence("agentic-workflow") == [
        {
            "id": "INC-7781/incident.lookup",
            "text": ops.execute("incident.lookup", {"incident_id": "INC-7781"}),
        },
        {
            "id": "INC-7781/network.site_status",
            "text": ops.execute("network.site_status", {"site_ids": sites}),
        },
    ]
    # 10: the document sample's own passages.
    copilot = catalog.scenario("document-copilot")
    assert copilot is not None and copilot.sample_artifact is not None
    assert evidence("document-copilot") == [e.model_dump() for e in copilot.sample_artifact.evidence]


def test_the_frontier_live_demo_pack_is_the_knowledge_base_as_ingested() -> None:
    """Scenario 12's pack: every chunk of fifteen KB documents, with the ids and text ingestion gives them, so
    retrieval adds no duplicates and the answer's passages are the ones the KB holds."""
    documents = {d.document_id: d for d in load_jsonl(Path(REPO_ROOT, "data/synthetic/kb/gct_kb.jsonl"))}
    expected: list[dict[str, str]] = []
    for number in [*range(141, 151), *range(211, 216)]:
        document = documents[f"GCT-POL-{number}"]
        texts = [
            evidence_text(document.document_id, n, document.title, heading, text)
            for section, (n, heading) in zip(document.sections, section_citations(document), strict=True)
            for text in chunk_section(section.text)
        ]
        expected += [{"id": f"{document.document_id}#{i}", "text": t} for i, t in enumerate(texts)]
    scenario = load_catalog(CONFIG).scenario("live-frontier-token-optimization")
    assert scenario is not None and scenario.sample_evidence is not None
    assert [e.model_dump() for e in scenario.sample_evidence] == expected
    assert any(
        "Call detail records shall be retained for a period of 12 months" in e["text"] for e in expected
    )


def _broken_config(tmp_path: Path, mutate) -> Path:  # type: ignore[no-untyped-def]
    target = tmp_path / "config"
    target.mkdir()
    for path in CONFIG.rglob("*"):
        if path.is_file():
            destination = target / path.relative_to(CONFIG)
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(path.read_bytes())
    data = yaml.safe_load((target / "scenarios.yaml").read_text(encoding="utf-8"))
    mutate({s["id"]: s for s in data["scenarios"]})
    (target / "scenarios.yaml").write_text(yaml.safe_dump(data), encoding="utf-8")
    return target


@pytest.mark.parametrize(
    ("mutate", "message"),
    [
        (lambda s: s["document-copilot"]["sample_artifact"]["figures"][0].update(value="413.6"), "is not in"),
        (
            lambda s: s["document-copilot"]["sample_artifact"]["figures"][0].update(source_id="nowhere"),
            "cites unknown",
        ),
        (lambda s: s["document-copilot"]["sample_artifact"].update(evidence=[]), "invalid sample request"),
        (lambda s: s["agentic-workflow"]["sample_workflow"].update(incident_id="7781"), "invalid sample"),
        (
            lambda s: s["network-operations"].update(
                sample_evidence=s["network-operations"]["sample_evidence"] * 4
            ),
            "invalid sample request",
        ),
        (
            lambda s: s["network-operations"]["sample_evidence"].append(
                s["network-operations"]["sample_evidence"][0]
            ),
            "duplicate sample evidence IDs",
        ),
    ],
)
def test_the_loader_rejects_samples_that_would_mislead_the_demo(tmp_path, mutate, message) -> None:  # type: ignore[no-untyped-def]
    with pytest.raises(ValueError, match=message):
        load_catalog(_broken_config(tmp_path, mutate))


async def test_the_catalog_api_exposes_the_samples(app_client) -> None:  # type: ignore[no-untyped-def]
    async with app_client("gct-doc-copilot") as client:
        scenarios = {s["id"]: s for s in (await client.get("/v1/catalog/scenarios")).json()}
    assert scenarios["document-copilot"]["sample_artifact"]["figures"][0]["id"] == "capex-total"
    assert scenarios["agentic-workflow"]["sample_workflow"]["incident_id"] == "INC-7781"
    assert scenarios["customer-support"]["sample_artifact"] is None
    assert len(scenarios["network-operations"]["sample_evidence"]) == 60
    assert scenarios["coding-assistant"]["sample_evidence"] is None
    assert all(s["quality_tier"] in {"standard", "high", "critical"} for s in scenarios.values())
    assert all(s["max_output_tokens"] >= 1 for s in scenarios.values())
    use_cases = [s["live_demo_use_case"] for s in scenarios.values() if s["live_demo_use_case"]]
    assert len(use_cases) == len(set(use_cases))
