/**
 * Generates the typed schema from the gateway's OpenAPI contract in <repo>/contracts
 * (openapi.json → src/schema.d.ts). A contract that does not exist yet is skipped
 * and its placeholder schema kept.
 */
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const TARGETS = [
  { contract: 'openapi.json', output: 'schema.d.ts' },
] as const;

for (const target of TARGETS) {
  const contract = new URL(`../../../../contracts/${target.contract}`, import.meta.url);
  const output = new URL(`../src/${target.output}`, import.meta.url);
  if (!existsSync(contract)) {
    console.log(`[api-client] ${fileURLToPath(contract)} does not exist yet; keeping ${target.output}.`);
    continue;
  }
  const ast = await openapiTS(contract);
  const banner = `// Generated by openapi-typescript from contracts/${target.contract}. Do not edit.\n\n`;
  await writeFile(output, banner + astToString(ast));
  console.log(`[api-client] Wrote ${fileURLToPath(output)}`);
}
