export type MessageKey = keyof typeof en;

export const t = createTranslator({ en });

/** Translates a message whose placeholders are React nodes, e.g. a link or a formatted ID. */
export const tRich = createRichTranslator(t);

/** Message keys with plural variants: `{base}.one`, `{base}.other` (and other CLDR categories as needed). */
type PluralBase = { [Key in MessageKey]: Key extends `${infer Base}.other` ? Base : never }[MessageKey];

/**
 * Translates a count-dependent message: picks `{base}.{category}` by the
 * locale's plural rules, falling back to `{base}.other`. `{count}` is filled
 * with the formatted count.
 */
export function tPlural(
  base: PluralBase,
  count: number,
  vars: Readonly<Record<string, string | number>> = {},
): string {
  const variant = `${base}.${pluralCategory(count)}`;
  const key = (variant in en ? variant : `${base}.other`) as MessageKey;
  return t(key, { ...vars, count: new Intl.NumberFormat('en').format(count) });
}
